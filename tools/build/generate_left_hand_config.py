"""Compile physical-unit detection parameters; no hardware/API operations."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate(check=False):
    source = ROOT / 'config/left_hand_detection.json'
    raw = source.read_bytes()
    c = json.loads(raw)
    p = c['profiles'][c['active_profile']]
    assert c['clock_hz'] == 50000000 and c['adc_half_div'] == 3
    assert c['direction'] in ('high', 'low')
    assert 1 <= p['window_rounds'] <= 20 and 0 <= c['release_percent'] <= c['press_percent'] <= 100
    assert len(c['channel_frets']) == 16 and all(0 <= n <= 16 for n in c['channel_frets'])
    assert 0 < c['threshold_v'] <= c['full_scale_v'] and 0 < c['channel0_threshold_v'] <= c['full_scale_v']
    # ADC128S102 and the reference volt_to_code use 4096 codes per span;
    # 4095 is the largest encodable code, not the voltage conversion span.
    threshold = min(4095, round(4096 * c['threshold_v'] / c['full_scale_v']))
    ch0 = min(4095, round(4096 * c['channel0_threshold_v'] / c['full_scale_v']))
    volts = c.get('thresholds_v', [c['channel0_threshold_v'] if i % 16 == 0 else c['threshold_v'] for i in range(64)])
    assert len(volts) == 64 and all(0 <= v <= c['full_scale_v'] for v in volts)
    # R12 差分判据：t_diff 单位是"码"，判 (peak - s2) >= t_diff。
    # 实测依据：静止 p99=62（含共模漂移 ±500 码后 max 仍 67），
    # 全 52 个有效格段内中位与 p10 在 120 时全部通过（弱格 399 码也能过）。
    assert 1 <= c.get('t_diff', 120) <= 4095, c.get('t_diff')
    assert c.get('use_diff', 1) in (0, 1, True, False)
    codes = [0 if v == 0 else min(4095, max(1, round(4096 * v / c['full_scale_v']))) for v in volts]
    thresholds = sum(code << (12 * i) for i, code in enumerate(codes))
    maps = sum(n << (5 * i) for i, n in enumerate(c['channel_frets']))
    values = dict(CLOCK_HZ=c['clock_hz'], SLOT_TICKS=p['slot_ticks'], SETTLE_TICKS=c['settle_ticks'],
                  CARRIER_HALF=c['carrier_half'], WINDOW=p['window_rounds'], PRESS=c['press_percent'],
                  RELEASE=c['release_percent'], COMMON=c['common_cells'], GROUP_SCANS=c['group_scans'],
                  DIRECTION_LOW=int(c['direction'] == 'low'),
                  USE_DIFF=int(c.get('use_diff', 1)), T_DIFF=c.get('t_diff', 120))
    body = '// Generated by scripts/generate_left_hand_config.py; edit config/left_hand_detection.json.\n'
    body += '// Config SHA256: ' + hashlib.sha256(raw).hexdigest() + '\n'
    body += '// Active profile: ' + c['active_profile'] + '; thresholds/mapping require board calibration.\n'
    body += '`ifndef LEFT_HAND_VOTE_CONFIG_VH\n`define LEFT_HAND_VOTE_CONFIG_VH\n'
    body += ''.join(f'`define LEFT_{key} {value}\n' for key, value in values.items())
    body += f"`define LEFT_THRESHOLDS 768'h{thresholds:0192x}\n"
    body += f"`define LEFT_CHANNEL_FRETS 80'h{maps:020x}\n`endif\n"
    target = ROOT / 'src/left_hand_vote_config.vh'
    if check:
        if not target.exists() or target.read_text(encoding='utf-8') != body:
            raise SystemExit('FAIL generated left-hand config is stale')
    else:
        target.write_text(body, encoding='utf-8')
    print(f'PASS config profile={c["active_profile"]} threshold={threshold} ch0={ch0} '
          f'slot={p["slot_ticks"]} window_rounds={p["window_rounds"]}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
