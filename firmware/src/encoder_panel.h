// ============================================================
// encoder_panel.h —— 4 路 EC11 旋转编码器（无源操作面板）驱动
//
// 面板来源：ProPrj_无源操作面板_2026-11-02.epro2
//   器件 4 × EC11E15244G1（ALPS 增量编码器，带按压开关）
//   网络 ENC1_A/B/SW … ENC4_A/B/SW 共 12 根信号，全部另一端接 GND
//   面板本身**没有上拉电阻、没有电源**，所以上拉必须由 ESP32 内部提供。
//
// 设计约束（决定了引脚表）：
//   1. 不能用 GPIO34..39 —— 它们只能输入、**没有内部上拉**，接 EC11 会浮空乱跳。
//   2. 不能用 GPIO6..11    —— 接 SPI Flash。
//   3. 不能用 GPIO16/17    —— 本工程已给 FPGA 链路 UART2。
//   4. 避开 GPIO0/2/12/15  —— strapping 脚，上电电平有特殊含义（尤其 12 影响 Flash 电压）。
//
// 解码方式：正交查表 + 4 象限算一格，机械抖动由表里的"非法跳变记 0"吸收，
// 再叠加 1 ms 采样节流；按键单独做 20 ms 稳定判定。全程不阻塞主循环。
// ============================================================
#pragma once
#include <Arduino.h>

namespace encpanel {

constexpr uint8_t kEncCount = 4;

// ---------------------------------------------------------------------------
// 3.5.9：引脚表（**以用户按原理图网络标签核对的结果为准**）
//
//   编码器          A        B        SW
//   ENC1（最左）    GPIO18   GPIO19   GPIO34
//   ENC2            GPIO23   GPIO25   GPIO35
//   ENC3            GPIO26   GPIO27   GPIO36
//   ENC4（最右）    GPIO33   GPIO32   GPIO39
//
// 其中的 GPIO 来源（两条独立证据，互相印证）：
//   ① 转接板 `ProPrj_电源端子转接板'_2026-11-03.epro2` 的 U1 符号 Pin Name：
//      pad9=D18 pad10=D19 pad19=D34 / pad15=D23 pad23=D25 pad20=D35 /
//      pad24=D26 pad25=D27 pad17=VP(36) / pad21=D32 pad22=D33 pad18=VN(39)。
//      交叉验证：pad6=ESP_RX=GPIO16、pad7=ESP_TX=GPIO17，与本工程 UART2 完全一致；
//      pad11/14=IMU_SDA/SCL 落在 GPIO21/22，与 I2C 一致。
//   ② 用户按两个工程的网络标签逐根核对（实板接线依据）。
//
// **唯一与 ① 有出入的是 ENC4 的 A/B：符号读出是 A=D32/B=D33，用户核对是 A=GPIO33/B=GPIO32。**
// 以用户为准（他手里是完整原理图 + 实物接线）。A/B 只影响旋转方向，
// 若实板方向相反，改 DELTA_SIGN 或把这两根对调即可，不影响其它三路。
//
// 曾经踩过的坑（务必不要再引入）：
//   3.5.8 有一版把表改成"面板 U11 与转接板 H9 网络整组反序"（即 ENC1 A=39 B=33 SW=32 …），
//   并把它设成默认。那是**假设排线同向压接**推出来的，与实物不符 ——
//   实板表现就是"四个旋钮全错位、转一下触发隔壁的按压"。已彻底删除，不再保留二选一宏。
//
// 上拉：SW 四路落在 GPIO34/35/36/39，这四个脚是纯输入、**没有内部上拉**。
// 转接板已用 R1..R4 把它们上拉到 ESP_3V3（PAD_NET：R1.1=ENC1_SW / R1.2=ESP_3V3，R2/R3/R4 同构），
// 所以 `pinMode(INPUT)` 即可，**不要再自己加电阻**。A/B 八根都是普通脚，走内部上拉。
// ---------------------------------------------------------------------------

// 每路 3 个引脚：A、B、按键(SW)
extern const uint8_t kPins[kEncCount][3];

// ---------------------------------------------------------------------------
// 3.5.10：接线自检
//
// 为什么需要它：**排线是 1-1 还是 1↔14，两个 HC-2510 座的文件里都查不到**
// （取决于压线方式）。两种接法下四个旋钮都能动，只是功能整体倒转，
// 所以"哪个旋钮干什么"没法从代码判断，只能看物理上哪根线在跳。
//
// 这里把 12 个编码器 GPIO 的电平边沿各自计数，网页上显示。
// 转**最左**旋钮，看哪两个脚在涨：
//    18/19 在涨  -> 反序排线（1↔14），kPins 用现在的表
//    39/33 在涨  -> 同向排线（1-1），需要把表整组换成 39/33/32 … 那一套
// 按最左旋钮，看哪个脚变 0：34 -> 反序；32 -> 同向。
//
// 12 个脚是两种接法的并集，与 kPins 的分组无关。
// ---------------------------------------------------------------------------
constexpr uint8_t kProbeCount = 12;
extern const uint8_t kProbePins[kProbeCount];
uint16_t probeEdges(uint8_t i);   // 自检用：该脚累计边沿数
void     probeReset();            // 清零（网页「清零」按钮）

// delta 单位是"格"。顺时针为正；方向反了改 encoder_panel.cpp 里的 DELTA_SIGN。
typedef void (*TurnCb)(uint8_t idx, int8_t delta);
typedef void (*ClickCb)(uint8_t idx);     // 短按：**松手时**回调（见下面"为什么改了时机"）
typedef void (*HoldCb)(uint8_t idx);      // 长按：按住达到 kHoldMs 时回调一次

// ---------------------------------------------------------------------------
// 3.5.2：新增长按，并把短按回调从"按下沿"改到"松手沿"
//
// 为什么必须改时机：
//   原来 click 是在**按下那一刻**就回调。这样长按会先触发一次短按动作
//   （例如 ENC4 会先把混响旁路切一次），1.5 s 后才轮到长按，副作用已经发生。
//   改成"松手时判定"之后：按住不放 = 只触发长按；快速点一下 = 只触发短按。
//   人的短按通常 80~150 ms，松手才响应感觉不到差别。
//
// 为什么阈值取 1.5 s：
//   要明显长于正常按压（<300 ms），又不能长到让人以为没反应。
//   1.5 s 是工业面板上常见的"长按确认"时长。
// ---------------------------------------------------------------------------
constexpr uint16_t kHoldMs = 1500;        // 长按阈值（ms）

void begin(TurnCb onTurn, ClickCb onClick, HoldCb onHold = nullptr);
void poll();                              // 在 loop() 里调用，内部按 1 ms 节流

uint32_t turnCount(uint8_t idx);          // 累计格数（诊断用）
uint32_t clickCount(uint8_t idx);

// 3.5.5：读某一路按键的**当前稳定电平**（1 = 未按，0 = 按下）。
// 这是判断"线接对了没有"最直接的东西：
//   正常静置时 4 路都应该是 1；哪一路是 0，就说明那一路的 SW 接到了 GND 或接错了。
uint8_t swLevel(uint8_t idx);

}  // namespace encpanel
